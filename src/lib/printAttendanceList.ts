export interface AttendanceListPerson {
  name: string;
  employeeCode?: string;
  department: string;
  designation: string;
  checkInTime?: string;
  checkOutTime?: string;
  breakMinutes?: number;
  lunchMinutes?: number;
  location?: string | null;
  statusLabel: string;
}

export interface AttendanceListReport {
  organization: string;
  dateLabel: string;
  generatedAt: string;
  /** "Absent" at the end of the day, "Not punched in yet" earlier. */
  absentLabel: string;
  absent: AttendanceListPerson[];
  present: AttendanceListPerson[];
  onLeave: AttendanceListPerson[];
  total: number;
}

const mins = (m?: number) => {
  const total = Math.round(Number(m) || 0);
  if (total <= 0) return "—";
  return total >= 60 ? `${Math.floor(total / 60)}h ${total % 60}m` : `${total}m`;
};

const esc = (value: unknown) =>
  String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const table = (title: string, tone: string, rows: AttendanceListPerson[], columns: "absent" | "present" | "leave") => {
  const head =
    columns === "present"
      ? "<th>#</th><th>Employee</th><th>Code</th><th>Department</th><th>Status</th><th>In</th><th>Out</th><th>Break</th><th>Lunch</th><th>Location</th>"
      : "<th>#</th><th>Employee</th><th>Code</th><th>Department</th><th>Designation</th>";
  const body = rows.length
    ? rows
        .map((p, i) =>
          columns === "present"
            ? `<tr><td>${i + 1}</td><td><b>${esc(p.name)}</b></td><td>${esc(p.employeeCode || "—")}</td><td>${esc(p.department)}</td><td>${esc(p.statusLabel)}</td><td>${esc(p.checkInTime || "—")}</td><td>${esc(p.checkOutTime || "—")}</td><td>${mins(p.breakMinutes)}</td><td>${mins(p.lunchMinutes)}</td><td>${esc(p.location || "—")}</td></tr>`
            : `<tr><td>${i + 1}</td><td><b>${esc(p.name)}</b></td><td>${esc(p.employeeCode || "—")}</td><td>${esc(p.department)}</td><td>${esc(p.designation)}</td></tr>`,
        )
        .join("")
    : `<tr><td colspan="10" class="empty">Nobody in this list.</td></tr>`;
  return `<section><h2 style="border-left-color:${tone}">${esc(title)} <span>${rows.length}</span></h2><table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table></section>`;
};

/** The printable page for the daily present / absent list. */
export function buildAttendanceListHtml(report: AttendanceListReport): string {
  return `<!doctype html><html><head><meta charset="utf-8"><title>Attendance ${esc(report.dateLabel)}</title>
<style>
  @page { size: A4 landscape; margin: 12mm 10mm; }
  * { box-sizing: border-box; }
  body { font-family: "Segoe UI", Arial, sans-serif; color: #0f172a; font-size: 11px; margin: 0; }
  header { display: flex; justify-content: space-between; align-items: flex-end; border-bottom: 2px solid #4f46e5; padding-bottom: 10px; margin-bottom: 14px; }
  h1 { font-size: 20px; margin: 0 0 2px; letter-spacing: -0.02em; }
  .muted { color: #64748b; }
  .org { font-size: 13px; font-weight: 700; color: #4f46e5; }
  .summary { display: flex; gap: 10px; margin-bottom: 16px; }
  .tile { flex: 1; border: 1px solid #e2e8f0; border-radius: 10px; padding: 8px 12px; }
  .tile b { display: block; font-size: 20px; }
  h2 { font-size: 13px; margin: 16px 0 6px; padding-left: 8px; border-left: 4px solid #4f46e5; }
  h2 span { color: #64748b; font-weight: 500; }
  table { width: 100%; border-collapse: collapse; }
  th { text-align: left; background: #f1f5f9; font-size: 10px; text-transform: uppercase; letter-spacing: .06em; color: #475569; }
  th, td { padding: 5px 7px; border-bottom: 1px solid #e2e8f0; vertical-align: top; }
  td, th { overflow-wrap: anywhere; }
  td:nth-child(n+5) { white-space: nowrap; }
  tr { page-break-inside: avoid; }
  thead { display: table-header-group; }
  .empty { text-align: center; color: #94a3b8; padding: 14px; }
  footer { margin-top: 18px; font-size: 10px; color: #94a3b8; }
</style></head><body>
<header>
  <div><div class="org">${esc(report.organization)}</div><h1>Daily attendance list</h1><div class="muted">${esc(report.dateLabel)}</div></div>
  <div class="muted" style="text-align:right">Generated ${esc(report.generatedAt)}</div>
</header>
<div class="summary">
  <div class="tile"><b>${report.total}</b>Total staff</div>
  <div class="tile"><b style="color:#059669">${report.present.length}</b>Present</div>
  <div class="tile"><b style="color:#e11d48">${report.absent.length}</b>${esc(report.absentLabel)}</div>
  <div class="tile"><b style="color:#0284c7">${report.onLeave.length}</b>On leave</div>
</div>
${table(report.absentLabel, "#e11d48", report.absent, "absent")}
${table("Present", "#059669", report.present, "present")}
${report.onLeave.length ? table("On leave", "#0284c7", report.onLeave, "leave") : ""}
<footer>Holidays and weekly offs are not counted as absent. Generated by WorkPluse.</footer>
</body></html>`;
}

/**
 * Opens the browser's print dialog for the report; choose "Save as PDF" to get the file.
 * An off-screen frame is used, so there is no pop-up window for a blocker to stop.
 */
export function printAttendanceList(report: AttendanceListReport) {
  const frame = document.createElement("iframe");
  frame.setAttribute("aria-hidden", "true");
  frame.style.cssText = "position:fixed;right:0;bottom:0;width:0;height:0;border:0;";
  document.body.appendChild(frame);
  const doc = frame.contentDocument;
  if (!doc || !frame.contentWindow) {
    frame.remove();
    throw new Error("Could not prepare the report for printing.");
  }
  doc.open();
  doc.write(buildAttendanceListHtml(report));
  doc.close();
  const win = frame.contentWindow;
  const cleanup = () => setTimeout(() => frame.remove(), 1000);
  win.addEventListener("afterprint", cleanup);
  // Give the frame a moment to lay out before the dialog opens.
  setTimeout(() => {
    win.focus();
    win.print();
  }, 250);
}
